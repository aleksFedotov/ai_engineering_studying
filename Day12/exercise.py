models = ["gpt-4o", "gpt-5"]



def extract_number(text: str):
    if not text:
        return None

    def to_float(s):
        s = s.strip().replace(" ", "").replace("\xa0", "").replace(",", ".")
        if not s:
            return None
        try:
            return float(s)
        except ValueError:
            return None

    # приоритет 1: маркер «Ответ: <число>» — перебираем с конца, пропуская пустые
    for m in reversed(re.findall(
            r"[Оо]твет[аы]?\s*[:—-]?\s*\*{0,2}\s*([\d\s]+(?:[.,]\d+)?)", text)):
        v = to_float(m)
        if v is not None:
            return v

    # приоритет 2: последнее число в тексте (фолбэк для zero-shot)
    nums = re.findall(r"\d+(?:[.,]\d+)?", text.replace("\xa0", " "))
    for n in reversed(nums):
        v = to_float(n)
        if v is not None:
            return v
    return None


def get_response(model:str, template: str, task_text:str): 
    prompt = template.replace("{ТЕКСТ ЗАДАЧИ}", task_text)
    try: 
        kwargs = dict(model=model, input=[{"role": "user", "content": prompt}])
        if model.startswith("gpt-4o"):
            kwargs["temperature"] = 0.0
        response = openai_client.responses.create(**kwargs)

        
        usage = response.usage
        details = getattr(usage, "output_tokens_details", None)
        return {
            "text": response.output_text,
            "output_tokens": getattr(usage, "output_tokens", 0),
            "reasoning_tokens": getattr(details, "reasoning_tokens", 0) if details else 0,
            "error": None,
        }
        

    except Exception as e:
        return {"text": "", "output_tokens": 0, "reasoning_tokens": 0,
                "error": f"{type(e).__name__}: {e}"}

rows = []
with open("results2.jsonl", encoding="utf-8") as f:
    for line in f:
        r = json.loads(line)
        r["pred"] = extract_number(r["text"])
        r["correct"] = (r["pred"] == ANSWER_KEY[r["task"]]) if r["pred"] is not None else False
        rows.append(r)
        print(f"{r['model']:7} | {r['prompt']:15} | {r['task']} | "
              f"ответ={r['pred']} | {'OK' if r['correct'] else 'FAIL'}")

done = {(r["model"], r["prompt"], r["task"]) for r in rows}
def main():
    with open("results2.jsonl", "w", encoding="utf-8") as log:
        for model in models:
            for template_name, template in templates.items():
                for task_name, task in tasks.items():
                    if (model, template_name, task_name) in done:
                        continue

                    r = get_response(model, template, task)
                    pred = extract_number(r["text"])
                    ok = (pred == ANSWER_KEY[task_name]) if pred is not None else False

                    # терминал: одна строка
                    print(f"{model:8} | {template_name:15} | {task_name} | "
                          f"ответ={pred} | {'OK ' if ok else 'FAIL'} | "
                          f"out={r['output_tokens']} | reas={r['reasoning_tokens']}"
                          + (f" | ERROR {r['error']}" if r['error'] else ""))

                    # полный текст — в лог
                    log.write(json.dumps({"model": model, "prompt": template_name,
                                          "task": task_name, "pred": pred, "correct": ok,
                                          **r}, ensure_ascii=False) + "\n")


if __name__ == "__main__":
    main()


    